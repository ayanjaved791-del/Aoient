import "server-only";
import { betterAuth } from "better-auth";
import { prismaAdapter } from "better-auth/adapters/prisma";
import { nextCookies } from "better-auth/next-js";
import { db } from "@/server/database/client";
import { getEmailProvider } from "@/server/email/provider";
import { resetPasswordMessage, verifyEmailMessage } from "@/server/email/templates";

/**
 * Identity is delegated to Better Auth (password hashing, sessions, email
 * verification, password reset, auth rate limits). Tenancy, roles and
 * permissions are Aoient's own (src/server/tenancy, src/server/permissions) so
 * they are enforced by one evaluator we control and test.
 */
export const auth = betterAuth({
  appName: "Aoient",
  baseURL: process.env.BETTER_AUTH_URL ?? process.env.APP_URL,
  secret: process.env.BETTER_AUTH_SECRET,
  trustedOrigins: process.env.APP_URL ? [process.env.APP_URL] : [],
  database: prismaAdapter(db, { provider: "postgresql" }),
  advanced: {
    // IDs are generated by Prisma (`@default(uuid(7))`).
    database: { generateId: false },
    useSecureCookies: process.env.NODE_ENV === "production",
  },
  user: {
    additionalFields: {
      status: { type: "string", required: false, defaultValue: "active", input: false },
    },
  },
  session: {
    expiresIn: 60 * 60 * 24 * 7, // 7 days
    updateAge: 60 * 60 * 24, // refresh expiry daily on use
  },
  emailAndPassword: {
    enabled: true,
    requireEmailVerification: true,
    minPasswordLength: 10,
    maxPasswordLength: 128,
    revokeSessionsOnPasswordReset: true,
    resetPasswordTokenExpiresIn: 60 * 60,
    sendResetPassword: async ({ user, url }) => {
      await getEmailProvider().send(resetPasswordMessage(user.email, url));
    },
  },
  emailVerification: {
    sendOnSignUp: true,
    sendOnSignIn: true,
    autoSignInAfterVerification: true,
    expiresIn: 60 * 60,
    sendVerificationEmail: async ({ user, url }) => {
      await getEmailProvider().send(verifyEmailMessage(user.email, user.name, url));
    },
  },
  rateLimit: {
    enabled: process.env.NODE_ENV !== "test",
    storage: "database",
    window: 60,
    max: 100,
    customRules: {
      "/sign-in/email": { window: 60, max: 5 },
      "/sign-up/email": { window: 60, max: 3 },
      "/request-password-reset": { window: 300, max: 3 },
      "/reset-password": { window: 300, max: 5 },
      "/send-verification-email": { window: 300, max: 3 },
    },
  },
  databaseHooks: {
    session: {
      create: {
        // Deactivated accounts cannot start new sessions.
        before: async (session) => {
          const user = await db.user.findUnique({ where: { id: session.userId }, select: { status: true } });
          if (!user || user.status !== "active") return false;
          return { data: session };
        },
      },
    },
  },
  plugins: [nextCookies()],
});

export type Auth = typeof auth;
