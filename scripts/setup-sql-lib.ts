import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { PERMISSIONS, SYSTEM_ROLES, SYSTEM_ROLE_KEYS } from "../src/server/permissions/catalog";

const DIR = join(process.cwd(), "supabase", "migrations");
const TAG = "$aoient_migration$";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: readonly string[]) => `array[${xs.map(lit).join(", ")}]::text[]`;

/**
 * Builds `supabase/setup.sql`: every migration plus the permission catalogue
 * and system roles, as one script to paste into the Supabase SQL Editor.
 * Safe to run again: applied migrations are skipped (same `schema_migration`
 * table as `npm run db:migrate`) and the seed is an idempotent upsert.
 */
export function buildSetupSql(): string {
  const out: string[] = [
    "-- Aoient database setup — GENERATED by `npm run db:setup-sql`. Do not edit by hand.",
    "-- Paste the whole file into Supabase → SQL Editor and click Run. Safe to run again",
    "-- after pulling new migrations: already-applied migrations are skipped.",
    "-- Equivalent to `npm run db:migrate && npm run db:seed`.",
    "",
    "begin;",
    "",
    "create table if not exists public.schema_migration (name text primary key, applied_at timestamptz not null default now());",
    "alter table public.schema_migration enable row level security;",
    "",
  ];

  for (const file of readdirSync(DIR).filter((f) => f.endsWith(".sql")).sort()) {
    const body = readFileSync(join(DIR, file), "utf8");
    if (body.includes(TAG)) throw new Error(`${file} contains ${TAG}`);
    out.push(
      `-- ─── Migration ${file} ───`,
      "do $aoient_setup$",
      "begin",
      `  if not exists (select 1 from public.schema_migration where name = ${lit(file)}) then`,
      `    execute ${TAG}`,
      body.trimEnd(),
      `${TAG};`,
      `    insert into public.schema_migration (name) values (${lit(file)});`,
      "  end if;",
      "end",
      "$aoient_setup$;",
      "",
    );
  }

  out.push("-- ─── Permission catalogue ───");
  for (const p of PERMISSIONS) {
    out.push(
      `insert into public.permission (key, description, module) values (${lit(p.key)}, ${lit(p.description)}, ${lit(p.module)})` +
        " on conflict (key) do update set description = excluded.description, module = excluded.module;",
    );
  }
  out.push(`delete from public.permission where key <> all(${arr(PERMISSIONS.map((p) => p.key))});`, "");

  out.push("-- ─── System roles ───");
  for (const key of SYSTEM_ROLE_KEYS) {
    const def = SYSTEM_ROLES[key];
    out.push(
      `update public.role set name = ${lit(def.name)}, description = ${lit(def.description)}, is_system = true, updated_at = now() where organization_id is null and key = ${lit(key)};`,
      `insert into public.role (key, name, description, is_system) select ${lit(key)}, ${lit(def.name)}, ${lit(def.description)}, true` +
        ` where not exists (select 1 from public.role where organization_id is null and key = ${lit(key)});`,
      `delete from public.role_permission where role_id = (select id from public.role where organization_id is null and key = ${lit(key)});`,
    );
    if (def.permissions.length > 0) {
      out.push(
        "insert into public.role_permission (role_id, permission_id)" +
          ` select r.id, p.id from public.role r, public.permission p where r.organization_id is null and r.key = ${lit(key)} and p.key = any(${arr(def.permissions)});`,
      );
    }
  }
  out.push("", "commit;", "");
  return out.join("\n");
}
